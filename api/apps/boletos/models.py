import uuid

from django.conf import settings
from django.db import models
from django.db.models import Q


class TipoInstrumento(models.TextChoices):
    BOLETO_BANCARIO = "boleto_bancario", "Boleto bancário"
    BOLETO_ARRECADACAO = "boleto_arrecadacao", "Boleto de arrecadação"
    PIX = "pix", "Pix"
    MANUAL = "manual", "Manual"


class Instrumento(models.Model):
    """Payment payload owned by one bill; read access always comes from that bill."""

    lancamento = models.OneToOneField(
        "lancamentos.Lancamento",
        on_delete=models.CASCADE,
        primary_key=True,
        related_name="instrumento",
    )
    tipo = models.CharField(max_length=20, choices=TipoInstrumento.choices)
    # NULL is the sole representation of an absent payload; the XOR constraint forbids "".
    codigo = models.CharField(max_length=4096, null=True, blank=True)  # noqa: DJ001
    chave_pix = models.CharField(max_length=77, null=True, blank=True)  # noqa: DJ001
    beneficiario = models.CharField(max_length=200, null=True, blank=True)  # noqa: DJ001

    data_emissao = models.DateField(null=True, blank=True)

    class Meta:
        constraints = [
            models.CheckConstraint(
                name="instrumento_tipo_conteudo_valido",
                condition=(
                    Q(
                        tipo=TipoInstrumento.BOLETO_BANCARIO,
                        codigo__regex=r"^[0-9]{47}$",
                        codigo__isnull=False,
                        chave_pix__isnull=True,
                    )
                    | Q(
                        tipo=TipoInstrumento.BOLETO_ARRECADACAO,
                        codigo__regex=r"^8[0-9]{47}$",
                        codigo__isnull=False,
                        chave_pix__isnull=True,
                    )
                    | Q(tipo=TipoInstrumento.MANUAL, codigo__isnull=True, chave_pix__isnull=True)
                    | (
                        Q(tipo=TipoInstrumento.PIX)
                        & (
                            (Q(codigo__isnull=False, chave_pix__isnull=True) & ~Q(codigo=""))
                            | (Q(codigo__isnull=True, chave_pix__isnull=False) & ~Q(chave_pix=""))
                        )
                    )
                ),
            )
        ]

    def __str__(self):
        # Never put the payload/key into cascade previews or incidental logs.
        return f"Instrumento ({self.get_tipo_display()})"


class DocumentoBoleto(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    espaco = models.ForeignKey("espacos.Espaco", on_delete=models.CASCADE)
    criado_por = models.ForeignKey(settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL)
    destino = models.ForeignKey(
        "lancamentos.Lancamento",
        null=True,
        blank=True,
        on_delete=models.CASCADE,
        related_name="pdfs_destinados",
    )
    lancamento = models.OneToOneField(
        "lancamentos.Lancamento",
        null=True,
        blank=True,
        on_delete=models.CASCADE,
        related_name="documento_pdf",
    )
    vinculado_em = models.DateTimeField(null=True, blank=True)
    estado = models.CharField(max_length=24, default="pendente")
    tentativa = models.UUIDField(null=True, editable=False)
    nome = models.CharField(max_length=200)
    tamanho = models.PositiveIntegerField()
    resultado = models.JSONField(default=dict)
    avisos = models.JSONField(default=list)
    criado_em = models.DateTimeField(auto_now_add=True)
    lido_em = models.DateTimeField(null=True, blank=True)

    def __str__(self):
        return f"Documento ({self.pk})"


class LimpezaPDF(models.Model):
    # IDs are generated by the server and identify immutable spool/object names.
    id = models.UUIDField(primary_key=True, editable=False)
    geracao = models.PositiveBigIntegerField(default=1)
    incerta = models.BooleanField(default=False)
    criado_em = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"Limpeza ({self.pk})"


class PinPDF(models.Model):
    # Operational capabilities outlive the originating user, bill and document.
    reserva_id = models.UUIDField(primary_key=True)
    documento_id = models.UUIDField(db_index=True)
    tamanho = models.PositiveIntegerField()

    def __str__(self):
        return "Pin de PDF"


class TentativaCopiaPDF(models.Model):
    id = models.UUIDField(primary_key=True, editable=False)
    reserva_id = models.UUIDField(db_index=True)
    fonte_id = models.UUIDField()
    destino_id = models.UUIDField(unique=True, default=uuid.uuid4, editable=False)
    estado = models.CharField(max_length=16, default="ativa")
    tamanho = models.PositiveIntegerField(null=True)
    sha256 = models.CharField(max_length=64, blank=True)
    # An interrupted PUT can still complete remotely after the client times out.
    incerta = models.BooleanField(default=True)

    def __str__(self):
        return "Tentativa de cópia de PDF"
